from pydantic import BaseModel, Field
from typing import List, Literal, Annotated, Optional

class Section(BaseModel):
    start_line: int = Field(description="Line number where this topic starts")
    topic: str = Field(description="Short name for the topic")
    parent: Optional[str] = Field(default=None, description="Parent topic name, or null")

class Sections(BaseModel):
    sections: List[Section]

class GeneratedQuestion(BaseModel):
    question: str = Field(description="The question generated by the llm")
    ideal_answer: str = Field(description="A correct answer")
    key_points: List[str] = Field(description="2-4 key ideas of correct answer")
    difficulty: int = Field(ge=1, le=5)

class GeneratedQuestions(BaseModel):
    questions: List[GeneratedQuestion] = Field(description="10 to 15 questions spread across difficulty levels 1-5")

class Question(BaseModel):
    """A question as it comes back OUT of the database.

    Distinct from GeneratedQuestion, which is what the LLM produces: this has
    the db-assigned question_id, the topic/parent attached at insert time, and
    uses the column name question_text rather than the schema's `question`.
    """
    question_id: int
    question_text: str
    ideal_answer: str
    key_points: List[str]
    difficulty: int = Field(ge=1, le=5)
    topic: str
    parent: Optional[str] = None

class GradeVerdict(BaseModel):
    verdict: Literal['correct', 'partial', 'wrong', 'dont_know', 'unclear']
    matched_points: List[str] = Field(default_factory=list)
    missed_points: List[str] = Field(default_factory=list)
    confidence: float = Field(ge=0.0, le=1.0)
    reasoning: str

    class Config:
        extra = 'forbid'
        anystr_strip_whitespace = True

class PageBlocks(BaseModel):
    blocks: List[str] = Field(
        description="List of raw, faithfully transcribed text, formulas, or code blocks from the page."
    )

class TopicChunk(BaseModel):
    parent: str = Field(
        description="Top-level concept (e.g., 'Divide and Conquer Method', 'Merge Sort', 'Master Method', 'Knapsack Problem')"
    )
    topic: Optional[str] = Field(
        None, 
        description="Specific sub-section (e.g., 'General Recurrence Derivation', 'Iterative Algorithm', 'Execution Trace Example')"
    )
    content: str = Field(
        description="Complete, merged text, formulas, and steps belonging to this topic/subtopic."
    )

class TopicCluster(BaseModel):
    canonical: str = Field(
        description="The single best name for this group of topics, taken from the variants themselves."
    )
    variants: List[str] = Field(
        description="Every topic name from the input that refers to this same topic, copied verbatim."
    )

class TopicClusters(BaseModel):
    clusters: List[TopicCluster] = Field(
        description="Groups of topic names that refer to the same underlying topic."
    )

class DocumentStructured(BaseModel):
    chunks: List[TopicChunk] = Field(
        description="List of all cohesive topic chunks extracted from the entire document."
    )
